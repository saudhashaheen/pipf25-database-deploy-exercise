-- One row in student per person. tools and availability are lists in the
-- CSV, stored here as many-to-many. position is the order in the cell (1 = first).

BEGIN;

CREATE TABLE student (
    student_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submitted_id text NOT NULL UNIQUE,
    full_name text NOT NULL,
    school_year text NOT NULL CHECK (school_year IN ('First-year', 'Sophomore', 'Junior', 'Senior')),
    intro_programming text NOT NULL CHECK (intro_programming IN ('took_it', 'equivalent', 'neither')),
    skill_programming smallint NOT NULL CHECK (skill_programming BETWEEN 1 AND 5),
    skill_data_stats smallint NOT NULL CHECK (skill_data_stats BETWEEN 1 AND 5),
    skill_frontend_design smallint NOT NULL CHECK (skill_frontend_design BETWEEN 1 AND 5),
    skill_business_pitch smallint NOT NULL CHECK (skill_business_pitch BETWEEN 1 AND 5),
    working_style text,
    interests text,
    semester_goal text,
    submitted_at timestamptz NOT NULL
);

CREATE TABLE tool (
    tool_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);

CREATE TABLE student_tool (
    student_id integer NOT NULL REFERENCES student (student_id) ON DELETE CASCADE,
    tool_id integer NOT NULL REFERENCES tool (tool_id) ON DELETE RESTRICT,
    position smallint NOT NULL CHECK (position >= 1),
    PRIMARY KEY (student_id, tool_id),
    UNIQUE (student_id, position)
);

CREATE TABLE availability_slot (
    period text NOT NULL CHECK (period IN ('Weekday', 'Weekend')),
    time_of_day text NOT NULL CHECK (time_of_day IN ('mornings', 'afternoons', 'evenings')),
    PRIMARY KEY (period, time_of_day)
);

CREATE TABLE student_availability (
    student_id integer NOT NULL REFERENCES student (student_id) ON DELETE CASCADE,
    period text NOT NULL,
    time_of_day text NOT NULL,
    position smallint NOT NULL CHECK (position >= 1),
    PRIMARY KEY (student_id, period, time_of_day),
    FOREIGN KEY (period, time_of_day) REFERENCES availability_slot (period, time_of_day) ON DELETE RESTRICT,
    UNIQUE (student_id, position)
);

INSERT INTO availability_slot (period, time_of_day) VALUES
    ('Weekday', 'mornings'),
    ('Weekday', 'afternoons'),
    ('Weekday', 'evenings'),
    ('Weekend', 'mornings'),
    ('Weekend', 'afternoons'),
    ('Weekend', 'evenings');

COMMIT;
